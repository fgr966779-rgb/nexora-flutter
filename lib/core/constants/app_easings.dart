/// Об'єднана крива з двох послідовних частин.
///
/// Перша половина анімації використовує [first] криву,
/// друга половина — [second] криву.
class _SequencedCurve extends Curve {
  /// Перша крива (для t: 0.0–0.5).
  final Curve first;

  /// Друга крива (для t: 0.5–1.0).
  final Curve second;

  const _SequencedCurve(this.first, this.second);

  @override
  double transformInternal(double t) {
    if (t < 0.5) {
      return first.transform(t * 2) * 0.5;
    }
    return second.transform((t - 0.5) * 2) * 0.5 + 0.5;
  }
}

/// Об'єднана крива з трьох послідовних частин.
///
/// Кожна третина використовує свою криву.
class _TripleSequencedCurve extends Curve {
  /// Перша крива (для t: 0.0–0.33).
  final Curve first;

  /// Друга крива (для t: 0.33–0.66).
  final Curve second;

  /// Третя крива (для t: 0.66–1.0).
  final Curve third;

  const _TripleSequencedCurve(this.first, this.second, this.third);

  @override
  double transformInternal(double t) {
    if (t < 0.333) {
      return first.transform(t * 3) * 0.333;
    } else if (t < 0.666) {
      return second.transform((t - 0.333) * 3) * 0.333 + 0.333;
    }
    return third.transform((t - 0.666) * 3) * 0.334 + 0.666;
  }
}

/// Зворотна крива — інвертує напрямок.
///
/// Ease-in стає ease-out і навпаки.
class _ReversedCurve extends Curve {
  /// Оригінальна крива для інверсії.
  final Curve original;

  const _ReversedCurve(this.original);

  @override
  double transformInternal(double t) {
    return 1.0 - original.transform(1.0 - t);
  }
}

/// Крива з обмеженням швидкості.
///
/// Зменшує швидкість зміни значення, роблячи анімацію повільнішою.
class _SpeedLimitedCurve extends Curve {
  /// Оригінальна крива.
  final Curve original;

  /// Множник швидкості (0.1–1.0).
  final double speedFactor;

  const _SpeedLimitedCurve(this.original, this.speedFactor);

  @override
  double transformInternal(double t) {
    // Застосовуємо non-linear маппінг для "сповільнення"
    final adjusted = t * speedFactor + (1.0 - speedFactor) * t * t;
    return original.transform(adjusted.clamp(0.0, 1.0));
  }
}
