  /// На початку шляху — повільна крива, ближче до цілі — швидша.
  /// Це створює відчуття "наближення до фінішу".
  ///
  /// [progress] — відсоток виконання цілі (0.0–1.0).
  ///
  /// Приклад:
  /// ```dart
  /// final curve = AppEasings.moodCurve(0.7); // → cubicOut
  /// ```
  static Curve moodCurve(double progress) {
    if (progress < 0.2) return slowEnd;
    if (progress < 0.5) return smooth;
    if (progress < 0.8) return cubicOut;
    return quartOut;
