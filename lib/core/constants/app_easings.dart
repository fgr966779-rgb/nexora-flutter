/// Криві анімацій (easing curves) для додатку Nexora.
///
/// Всі криві згруповані за категоріями для зручного пошуку:
/// - **Базові (Core)** — стандартні криві Flutter з семантичними назвами.
/// - **Розширені (Extended)** — додаткові кубічні криві для тонкого налаштування.
/// - **Гейміфікація (Gamification)** — криві для святкувань, нагород, досягнень.
/// - **Тематичні (Themed)** — набори для PS5 неонової та Monitor морозної тем.
/// - **Переходи сторінок (Page Transitions)** — для навігації між екранами.
/// - **Фізичні (Physics-based)** — пружинні та гравітаційні криві.
/// - **Інтерактивні (Interactive)** — для перетягування, гортання, жестів.
/// - **3D / Трансформації** — для обертання, масштабу, перспективи.
/// - **Каскадні (Staggered)** — для послідовних анімацій списків.
/// - **Мікроанімації (Micro)** — для дрібних змін стану UI.
/// - **Розмірні (Size Change)** — для зміни ширини/висоти.
/// - **Непрозорість (Opacity)** — для fade-ефектів.
library;

import 'package:flutter/animation.dart';

/// Клас із статичними константами кривих анімацій.
///
/// Використовується по всьому додатку для єдиної анімаційної мови.
/// Кожна крива має семантичну назву та докладний опис.
class AppEasings {
  AppEasings._();

  // ═══════════════════════════════════════════════════════════════════════
  // Базові криві (Core Easings)
  // ═══════════════════════════════════════════════════════════════════════

  /// Стандартна симетрична крива — більшість UI-переходів.
  ///
  /// Найуніверсальніша крива для будь-яких переходів:
  /// зміна кольорів, розмірів, позицій.
  static const Curve standard = Curves.easeInOut;

  /// Гальмування (ease-out) — для елементів, що з'являються.
  ///
  /// Ідеально для входу карток, списків, модальних вікон.
  static const Curve decelerate = Curves.decelerate;

  /// Прискорення (ease-in) — для елементів, що зникають.
  ///
  /// Використовується при виході елементів з екрану.
  static const Curve accelerate = Curves.easeIn;

  /// Відбій — грайливі взаємодії, бейджі, досягнення.
  ///
  /// Дає ефект "живого" інтерфейсу для нескладних елементів.
  static const Curve bounce = Curves.bounceOut;

  /// Пружинний ефект — конфетті, spring-анімації.
  ///
  /// Використовується для ефектів, що мають перебільшувати ціль.
  static const Curve elastic = Curves.elasticOut;

  /// Пружина / оверсхот — вхід модальних вікон, спливання карток.
  ///
  /// Легкий перебіг за ціль із поверненням на місце.
  static const Curve spring = Curves.easeOutBack;

  /// Плавний Material-подібний перехід.
  ///
  /// Стандартна крива Material Design для плавних переходів.
  static const Curve smooth = Cubic(0.4, 0.0, 0.2, 1.0);

  /// Легкий оверсхот для мікро-взаємодій.
  ///
  /// Помітний, але не руйнівний — для кнопок, чекбоксів, перемикачів.
  static const Curve overshoot = Cubic(0.175, 0.885, 0.32, 1.275);

  // ═══════════════════════════════════════════════════════════════════════
  // Розширені загальні криві (Extended General Easings)
  // ═══════════════════════════════════════════════════════════════════════

  /// М'який відбій — грація без повного пружинного ефекту.
  ///
  /// Краще за [bounce] для більш серйозних, але привабливих UI.
  static const Curve gentleBounce = Cubic(0.34, 1.56, 0.64, 1.0);

  /// Різкий, швидкий відбій — миттєвий зворотний зв'язок.
  ///
  /// Для швидких дій: натискання, підтвердження, вибір.
  static const Curve sharpBounce = Cubic(0.18, 0.89, 0.32, 1.46);

  /// Повільний старт для драматичних появ.
  ///
  /// Починається дуже плавно, потім пришвидшується —
  /// ідеально для "відривання" елементів з місця.
  static const Curve slowStart = Cubic(0.55, 0.0, 0.1, 1.0);

  /// Повільне завершення для плавних зникнень.
  ///
  /// Швидкий старт, плавне гальмування до кінця.
  static const Curve slowEnd = Cubic(0.0, 0.0, 0.2, 1.0);

  /// Драматичний відгін назад, потім ривок — кінематографічні розкриття.
  ///
  /// Ефект "натягування гуми" перед рухом вперед.
  static const Curve dramaticEntrance = Cubic(0.7, 0.0, 0.3, 1.0);

  /// Легкий сплеск — бейджі сповіщень, малі іконки.
  ///
  /// Мінімальний оверсхот, помітний при уважному погляді.
  static const Curve subtlePop = Cubic(0.2, 1.4, 0.4, 1.0);

  /// Плавна пружина без оверсхоту — безпечна для layout-анімацій.
  ///
  /// Не змінює розміри елементів, лише прискорення/гальмування.
  static const Curve smoothSpring = Cubic(0.25, 0.46, 0.45, 0.94);

  /// М'яка ease-in-out — плавні, ненав'язливі переходи.
  ///
  /// Для зміни станів, що не привертають увагу.
  static const Curve soft = Cubic(0.42, 0.0, 0.58, 1.0);

  /// Різке гальмування — швидке "приземлення".
  ///
  /// Для елементів, що мають миттєво зупинитися.
  static const Curve sharpDecel = Cubic(0.0, 0.0, 0.2, 1.0);

  /// Квадратичне гальмування — стандартне "ігрове" відчуття.
  ///
  /// Найчастіша крива в ігрових анімаціях.
  static const Curve quadOut = Cubic(0.25, 0.46, 0.45, 0.94);

  /// Кубічне гальмування — більш драматичне сповільнення.
  ///
  /// Сильніше гальмування, ніж [quadOut], для видимих елементів.
  static const Curve cubicOut = Cubic(0.22, 0.61, 0.36, 1.0);

  /// Четвертне гальмування — сильне сповільнення.
  ///
  /// Елемент ніби "врізається" у ціль із силою.
  static const Curve quartOut = Cubic(0.16, 1.0, 0.3, 1.0);

  /// Експоненційне гальмування — дуже сильне сповільнення.
  ///
  /// Максимальне гальмування — елемент зупиняється різко.
  static const Curve expoOut = Cubic(0.0, 0.0, 0.1, 1.0);

  /// Лінійна крива — без прискорення або гальмування.
  ///
  /// Використовується для прогрес-барів та механічних анімацій.
  static const Curve linear = Curves.linear;

  /// Лінійне з нульовою затримкою — аналог [linear].
  ///
  /// Синонім для читабельності коду.
  static const Curve linearZero = Curves.linear;

  /// Плавне прискорення (ease-in) — стандартне.
  ///
  /// Для входу анімацій з місця, розгортання елементів.
  static const Curve easeIn = Cubic(0.42, 0.0, 1.0, 1.0);

  /// Плавне гальмування (ease-out) — стандартне.
  ///
  /// Найчастіша крива для виходу елементів.
  static const Curve easeOut = Cubic(0.0, 0.0, 0.58, 1.0);

  // ═══════════════════════════════════════════════════════════════════════
  // Пружинні фізичні криві (Physics-Based Spring Curves)
  // ═══════════════════════════════════════════════════════════════════════

  /// Легка пружина — м'який відбій із мінімальним оверсхотом.
  ///
  /// Для елементів, що потребують "дихання", але не "стрибка".
  static const Curve lightSpring = Cubic(0.22, 1.0, 0.36, 1.0);

  /// Середня пружина — помірний оверсхот і стабілізація.
  ///
  /// Баланс між грою та професійністю.
  static const Curve mediumSpring = Cubic(0.175, 0.885, 0.32, 1.1);

  /// Важка пружина — значний оверсхот, повільна стабілізація.
  ///
  /// Для виділених елементів, що привертають увагу.
  static const Curve heavySpring = Cubic(0.34, 1.8, 0.64, 1.0);

  /// Гнучка пружина — кілька коливань перед стабілізацією.
  ///
  /// Дає ефект "желейності" — для гейміфікованих елементів.
  static const Curve wobblySpring = Cubic(0.5, 2.0, 0.5, 0.8);

  /// Гумова стрічка — тягучий еластичний ефект.
  ///
  /// Елемент ніби розтягується перед поверненням.
  static const Curve rubberBand = Cubic(0.0, 1.2, 0.4, 1.0);

  /// Падіння під гравітацією — прискорення, потім раптова зупинка.
  ///
  /// Імітація падіння об'єкта.
  static const Curve gravityDrop = Cubic(0.6, 0.0, 1.0, 0.4);

  /// Відбій при приземленні — кілька малих відскоків.
  ///
  /// Імітація м'яча, що падає та підстрибує.
  static const Curve bouncyLanding = Cubic(0.2, 1.6, 0.6, 0.9);

  /// Мінімальна вібрація — легке тремтіння в кінці.
  ///
  /// Для фінальної фази анімацій, що потребують "тонусу".
  static const Curve microVibrate = Cubic(0.1, 0.9, 0.2, 1.02);

  // ═══════════════════════════════════════════════════════════════════════
  // Криві гейміфікації (Gamification Easings)
  // ═══════════════════════════════════════════════════════════════════════

  /// Кінематографічна крива — завершення цілей, довгі розкриття.
  ///
  /// Плавне, але виразне рухіння для важливих подій.
  static const Curve cinematicEase = Cubic(0.22, 1.0, 0.36, 1.0);

  /// Пульсація неонового сяйва — м'яка ease-in-out із "утриманням".
  ///
  /// Для неонових ефектів PS5-теми.
  static const Curve neonGlow = Cubic(0.45, 0.0, 0.55, 1.0);

  /// Танення криги — швидкий старт, повільне замерзання в кінці.
  ///
  /// Для морозної теми Monitor — імітація танення.
  static const Curve frostMelt = Cubic(0.0, 0.8, 0.2, 1.0);

  /// Вибух феєрверку — вибуховий старт, повільне згасання.
  ///
  /// Для святкових ефектів, конфетті, феєрверків.
  static const Curve fireworkBurst = Cubic(0.0, 0.6, 0.4, 1.0);

  /// Падіння конфетті — прискорення під гравітацією.
  ///
  /// Імітація природного падіння конфетті.
  static const Curve confettiFall = Cubic(0.55, 0.0, 1.0, 0.45);

  /// Заповнення прогрес-бару — плавне гальмування.
  ///
  /// Для шкал прогресу цілей та викликів.
  static const Curve progressEase = Cubic(0.0, 0.0, 0.2, 1.0);

  /// Лічильник грошей — швидкий старт, стабілізація в кінці.
  ///
  /// Для анімації count-up числових значень.
  static const Curve moneyCount = Cubic(0.16, 1.0, 0.3, 1.0);

  /// Підвищення рівня — драматичний оверсхот.
  ///
  /// Для level-up ефектів, що мають вразити користувача.
  static const Curve levelUp = Cubic(0.34, 1.8, 0.64, 1.0);

  /// Розблокування бейджу — пружинний "щёлк" на місце.
  ///
  /// Еластичний ефект "встрибування" бейджу в позицію.
  static const Curve badgeUnlock = Curves.elasticOut;

  /// Мерехтіння вогню серії — швидка пульсація.
  ///
  /// Для іконки серії (streak fire) — живий вогонь.
  static const Curve streakFire = Cubic(0.4, 0.0, 0.2, 1.0);

  /// Заморожування — крижане гальмування (морозний настрій).
  ///
  /// Для ефекту "заморожування" при розриві серії.
  static const Curve freezeIn = Cubic(0.0, 0.9, 0.3, 1.0);

  /// Розморозка — танення/вивільнення із пружиною.
  ///
  /// Для відновлення серії після розриву.
  static const Curve unfreezeOut = Cubic(0.2, 1.2, 0.4, 1.0);

  /// Перехід теми — кросфейд між PS5 та Monitor темами.
  ///
  /// Плавна зміна кольорів при перемиканні тем.
  static const Curve themeTransition = Cubic(0.4, 0.0, 0.6, 1.0);

  /// Обертання монети — відчуття ротації для монеток.
  ///
  /// Імітація обертання монети при отриманні.
  static const Curve coinSpin = Cubic(0.0, 0.7, 0.2, 1.0);

  /// Заповнення XP-шки — плавне прискорення потім гальмування.
  ///
  /// Для шкал досвіду користувача.
  static const Curve xpBarFill = Cubic(0.4, 0.0, 0.2, 1.0);

  /// Збирання зірки — швидке "зхоплення" для зірок/досягнень.
  ///
  /// Для анімації збирання зірки на картці досягнень.
  static const Curve starCollect = Cubic(0.15, 1.5, 0.5, 1.0);

  /// Відкриття скрині нагород — драматичний ефект відкриття.
  ///
  /// Для анімації скриньки з нагородами.
  static const Curve rewardChest = Cubic(0.68, -0.55, 0.27, 1.55);

  /// Збирання монет — "присмоктування" до бейджу.
  ///
  /// Для анімації збирання монеток на екрані.
  static const Curve coinCollect = Cubic(0.0, 0.5, 0.3, 1.0);

  /// Ефект комбо — пришвидшення з кожним кроком.
  ///
  /// Для лічильника комбо при серійних діях.
  static const Curve comboAccel = Cubic(0.1, 0.8, 0.2, 1.0);

  /// Розблокування челенджу — феєричний вхід.
  ///
  /// Для моменту розблокування нового виклику.
  static const Curve challengeUnlock = Cubic(0.25, 1.5, 0.5, 1.0);

  // ═══════════════════════════════════════════════════════════════════════
  // Криві переходів сторінок (Page Transition Easings)
  // ═══════════════════════════════════════════════════════════════════════

  /// Натискання сторінки — плавний вхід справа.
  ///
  /// Стандартний перехід для навігації вперед.
  static const Curve pagePush = Cubic(0.2, 0.0, 0.0, 1.0);

  /// Вихід сторінки — зсув вправо.
  ///
  /// Стандартний перехід для повернення назад.
  static const Curve pagePop = Cubic(0.2, 0.0, 0.0, 1.0);

  /// З'явлення модального вікна — зсув вгору з гальмуванням.
  ///
  /// Для bottom sheet, діалогів, модалок.
  static const Curve modalPresent = Cubic(0.0, 0.0, 0.2, 1.0);

  /// Зникнення модального вікна — зсув вниз із прискоренням.
  ///
  /// Для закриття модальних елементів.
  static const Curve modalDismiss = Cubic(0.4, 0.0, 0.6, 1.0);

  /// З'явлення нижнього листа — пружинний зсув вгору.
  ///
  /// Для drag-to-dismiss листів із snap points.
  static const Curve sheetAppear = Cubic(0.2, 1.0, 0.3, 1.0);

  /// Вхід діалогу — комбінований масштаб + затухання.
  ///
  /// Для AlertDialog, що з'являється в центрі екрану.
  static const Curve dialogEnter = Cubic(0.175, 0.885, 0.32, 1.125);

  /// Вихід діалогу — швидке зменшення масштабу.
  ///
  /// Для закриття діалогів — швидко та акуратно.
  static const Curve dialogExit = Cubic(0.4, 0.0, 1.0, 1.0);

  /// Перемикання вкладок — горизонтальний зсув між табами.
  ///
  /// Для PageView у TabBar та carousel.
  static const Curve tabSwitch = Cubic(0.4, 0.0, 0.2, 1.0);

  /// Hero-перехід — плавний морфінг між екранами.
  ///
  /// Для Hero-анімацій Flutter.
  static const Curve heroMorph = Cubic(0.0, 0.0, 0.2, 1.0);

  /// Вхід зі зсувом знизу — для bottom-to-top навігації.
  ///
  /// Альтернатива [modalPresent] для повноекранних вікон.
  static const Curve slideUp = Cubic(0.0, 0.0, 0.2, 1.0);

  /// Вхід зі зсувом зліва — для right-to-left навігації.
  ///
  /// Для RTL-локалей або альтернативного напрямку.
  static const Curve slideFromLeft = Cubic(0.2, 0.0, 0.0, 1.0);

  // ═══════════════════════════════════════════════════════════════════════
  // Криві гортання та перетягування (Scroll & Drag Easings)
  // ═══════════════════════════════════════════════════════════════════════

  /// Імпульс гортання — природне гальмування після fling.
  ///
  /// Для ScrollView після відпускання пальцем.
  static const Curve scrollMomentum = Cubic(0.0, 0.0, 0.2, 1.0);

  /// Фіксація гортання — стабілізація на позиції.
  ///
  /// Для PageView snapping або Carousel snapping.
  static const Curve scrollSnap = Cubic(0.2, 0.0, 0.0, 1.0);

  /// Початок перетягування — повільний "підхоплення".
  ///
  /// Для drag gesture при початку руху.
  static const Curve dragStart = Cubic(0.4, 0.0, 0.2, 1.0);

  /// Відпускання перетягування — швидке повернення або рух.
  ///
  /// Для snap-back або continuation після drag.
  static const Curve dragRelease = Cubic(0.0, 0.0, 0.2, 1.0);

  /// Відкриття свайпом — плавний зсув із гальмуванням.
  ///
  /// Для swipe-to-reveal (наприклад, видалення).
  static const Curve swipeReveal = Cubic(0.25, 0.1, 0.25, 1.0);

  /// Pull-to-refresh — відчуття перетягування із snap.
  ///
  /// Для pull-to-refresh жесту в списках.
  static const Curve pullRefresh = Cubic(0.4, 0.0, 0.2, 1.0);

  /// Відбій при overscroll — гумовий оверсхот.
  ///
  /// Для ефекту "гумової стрічки" при over-scroll.
  static const Curve overscrollBounce = Cubic(0.0, 0.8, 0.2, 1.0);

  /// Pinch-to-zoom — плавне масштабування пальцями.
  ///
  /// Для жесту збільшення зображень або карт.
  static const Curve pinchZoom = Cubic(0.2, 0.0, 0.2, 1.0);

  /// Довге натискання — повільне наростання ефекту.
  ///
  /// Для long-press анімацій (наприклад, ReorderableListView).
  static const Curve longPress = Cubic(0.4, 0.0, 0.2, 1.0);

  // ═══════════════════════════════════════════════════════════════════════
  // Криві 3D / Трансформації (3D / Transform Easings)
  // ═══════════════════════════════════════════════════════════════════════

